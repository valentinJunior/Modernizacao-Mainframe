-- Espelho das tabelas DB2 usadas pelo job JURD0100, mais a tabela de spread
-- que no legado estava fixa no codigo da JURS0100.

CREATE TABLE TB_TAXA_PRODUTO (
    ID              BIGINT        NOT NULL PRIMARY KEY,
    CD_PRODUTO      CHAR(3)       NOT NULL,
    DS_PRODUTO      VARCHAR(30)   NOT NULL,
    PC_TAXA_MENSAL  DECIMAL(7,4)  NOT NULL,
    PC_MORA_MENSAL  DECIMAL(7,4)  NOT NULL,
    PC_MULTA        DECIMAL(7,4)  NOT NULL,
    DT_INI_VIGENCIA DATE          NOT NULL,
    DT_FIM_VIGENCIA DATE          NOT NULL
);

CREATE INDEX IX_TAXA_PRODUTO_VIGENCIA
    ON TB_TAXA_PRODUTO (CD_PRODUTO, DT_INI_VIGENCIA, DT_FIM_VIGENCIA);

CREATE TABLE TB_SPREAD_RATING (
    ID               BIGINT        NOT NULL PRIMARY KEY,
    CD_RATING        VARCHAR(2)    NOT NULL,
    PC_SPREAD_MENSAL DECIMAL(7,4)  NOT NULL,
    DT_INI_VIGENCIA  DATE          NOT NULL,
    DT_FIM_VIGENCIA  DATE          NOT NULL
);

CREATE INDEX IX_SPREAD_RATING_VIGENCIA
    ON TB_SPREAD_RATING (CD_RATING, DT_INI_VIGENCIA, DT_FIM_VIGENCIA);
